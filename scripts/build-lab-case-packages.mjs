import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { validateLabCase } from "./validate-lab-case.mjs";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const defaultCaseDirectory = path.join(projectRoot, "content", "lab-cases", "car-control", "v2");
const privateOutputPath = path.join(projectRoot, "prototype", "worker", "generated", "lab-case-private.generated.ts");
const publicOutputPath = path.join(projectRoot, "prototype", "lib", "lab", "lab-case-public.generated.ts");

const sourceFiles = {
  workloadPlan: "workload-plan.json",
  schedulePlan: "schedule-plan.json",
  stakeholderPlan: "stakeholder-plan.json",
  documentPlan: "document-plan.json",
  requirementPlan: "requirement-plan.json",
  riskPlan: "risk-plan.json",
  qualityPlan: "quality-plan.json",
  scenarioPlan: "scenario-plan.json",
  baselineWorkload: "baseline-workload.generated.json",
};

const forbiddenPublicKeys = new Set([
  "aiReviewPolicy",
  "branchComparisonPolicy",
  "completedEffect",
  "consequenceId",
  "engineSettlementPolicy",
  "evaluationRole",
  "harmfulConsequences",
  "harmfulEffectsStack",
  "idealDecision",
  "idealOutcome",
  "incompleteOutcomePolicy",
  "initialImpact",
  "managementLoad",
  "minimumCorrectCardIds",
  "minimumCorrectConnections",
  "missingActionConsequences",
  "necessaryManagementActions",
  "requiredObservations",
  "satisfiesActionIds",
  "scenarioOverrides",
  "terminalRules",
  "unresolvedIssueDegradation",
]);

function stableValue(value) {
  if (Array.isArray(value)) return value.map(stableValue);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stableValue(value[key])]));
}

function withoutKeys(value, keys) {
  return Object.fromEntries(Object.entries(value).filter(([key]) => !keys.includes(key)));
}

function assertPublicProjectionSafe(value, pathParts = []) {
  if (Array.isArray(value)) {
    value.forEach((item, index) => assertPublicProjectionSafe(item, [...pathParts, String(index)]));
    return;
  }
  if (!value || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    const location = [...pathParts, key].join(".");
    if (forbiddenPublicKeys.has(key)) throw new Error(`Private field leaked into public projection: ${location}`);
    assertPublicProjectionSafe(child, [...pathParts, key]);
  }
}

function moduleSource(typeName, exportName, value) {
  const serialized = JSON.stringify(value, null, 2).replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");
  return `// Generated by scripts/build-lab-case-packages.mjs. Do not edit by hand.\n\nimport type { ${typeName} } from "${exportName === "privateLabCasePackage" ? "../../lib/lab/contracts" : "./contracts"}";\n\nexport const ${exportName}: ${typeName} = ${serialized};\n`;
}

export async function buildLabCasePackages(caseDirectory = defaultCaseDirectory) {
  await validateLabCase(caseDirectory);

  const entries = await Promise.all(Object.entries(sourceFiles).map(async ([key, filename]) => [
    key,
    JSON.parse(await readFile(path.join(caseDirectory, filename), "utf8")),
  ]));
  const source = Object.fromEntries(entries);
  const canonicalSource = stableValue(source);
  const contentHash = createHash("sha256").update(JSON.stringify(canonicalSource)).digest("hex");
  const identity = {
    schemaVersion: 1,
    caseId: source.workloadPlan.caseId,
    caseVersion: source.workloadPlan.caseVersion,
    contentHash,
  };

  const privatePackage = { ...identity, sourceFiles: source };
  const publicProjection = {
    ...identity,
    totalWeeks: source.workloadPlan.totalWeeks,
    plans: {
      workload: source.workloadPlan,
      schedule: source.schedulePlan,
      stakeholders: source.stakeholderPlan,
      documents: source.documentPlan,
      requirements: source.requirementPlan,
      risks: withoutKeys(source.riskPlan, ["scenarioOverrides"]),
      quality: withoutKeys(source.qualityPlan, ["scenarioOverrides"]),
      baselineWorkload: source.baselineWorkload,
    },
    learningPolicies: {
      eventDiscovery: source.scenarioPlan.eventDiscoveryPolicy,
      decisionReasoning: source.scenarioPlan.decisionReasoningPolicy,
    },
    takeoverPoints: source.scenarioPlan.scenarios.map((scenario) => ({
      scenarioId: scenario.id,
      week: scenario.week,
      label: "从这里接手",
    })),
  };

  assertPublicProjectionSafe(publicProjection);
  await Promise.all([
    mkdir(path.dirname(privateOutputPath), { recursive: true }),
    mkdir(path.dirname(publicOutputPath), { recursive: true }),
  ]);
  await Promise.all([
    writeFile(privateOutputPath, moduleSource("PrivateLabCasePackage", "privateLabCasePackage", privatePackage)),
    writeFile(publicOutputPath, moduleSource("PublicLabCaseBaseline", "publicLabCaseBaseline", publicProjection)),
  ]);

  return {
    caseId: identity.caseId,
    caseVersion: identity.caseVersion,
    contentHash,
    privateOutputPath,
    publicOutputPath,
  };
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : null;
if (invokedPath === import.meta.url) {
  const result = await buildLabCasePackages(process.argv[2] ? path.resolve(process.argv[2]) : defaultCaseDirectory);
  console.log(`Built private and public packages for ${result.caseId}:${result.caseVersion} (${result.contentHash.slice(0, 12)}).`);
}
