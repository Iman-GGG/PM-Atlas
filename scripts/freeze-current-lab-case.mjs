import { access, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const publicModulePath = path.join(projectRoot, "prototype", "lib", "lab", "lab-case-public.generated.ts");
const privateModulePath = path.join(projectRoot, "prototype", "worker", "generated", "lab-case-private.generated.ts");

const [{ publicLabCaseBaseline }, { privateLabCasePackage }] = await Promise.all([
  import(pathToFileURL(publicModulePath).href),
  import(pathToFileURL(privateModulePath).href),
]);

if (
  publicLabCaseBaseline.caseVersion !== privateLabCasePackage.caseVersion
  || publicLabCaseBaseline.contentHash !== privateLabCasePackage.contentHash
) {
  throw new Error("The current public and private packages do not describe the same immutable case version.");
}

const versionSuffix = publicLabCaseBaseline.caseVersion.replace(/[^A-Za-z0-9]/g, "");
const exportName = `frozenLabCase${versionSuffix.toUpperCase()}RuntimePackage`;
const outputPath = path.join(
  projectRoot,
  "prototype",
  "worker",
  "generated",
  `lab-case-${publicLabCaseBaseline.caseVersion}-frozen.generated.ts`,
);

try {
  await access(outputPath);
  throw new Error(`Frozen case package already exists: ${outputPath}`);
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

const runtime = {
  ...publicLabCaseBaseline,
  scenarios: privateLabCasePackage.sourceFiles.scenarioPlan.scenarios,
};
const serialized = JSON.stringify(runtime, null, 2).replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");
const source = `// Generated by scripts/freeze-current-lab-case.mjs. Do not edit by hand.\n\nimport type { LabCaseRuntimePackage } from "../../lib/lab/contracts";\n\nexport const ${exportName}: LabCaseRuntimePackage = ${serialized};\n`;

await writeFile(outputPath, source);
console.log(`Frozen ${publicLabCaseBaseline.caseId}:${publicLabCaseBaseline.caseVersion} at ${publicLabCaseBaseline.contentHash.slice(0, 12)}.`);
